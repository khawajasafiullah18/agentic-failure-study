# Keyword evidence for each research question. Two cues are deliberate: "why"
# and "cause" route to the causal analysis, which is the only place the study
# discusses causes, and those findings are graded by evidence rather than
# asserted. Wording here is the routing table, not an answer.
_INTENTS: dict[str, tuple[str, ...]] = {
    "RQ1": ("distribution", "how many", "share", "proportion", "breakdown",
            "frequency", "most common", "categories", "what kinds", "types"),
    "RQ2": ("dominant", "largest", "biggest", "rank", "precisely", "interval",
            "confident", "confidence"),
    "RQ3": ("cause", "causes", "caused", "why", "reason", "root", "associated",
            "association", "mechanism"),
    "RQ4": ("framework", "frameworks", "differ", "difference", "compare",
            "composition", "per framework", "between frameworks"),
    "RQ5": ("blocking", "severity", "severe", "crash", "hard stop", "how bad",
            "stop the run"),
    "RQ6": ("complexity", "complex", "tier", "sophisticated", "architecture",
            "orchestration rate"),
    "RQ7": ("silent", "escape", "escapes", "undetected", "caught", "runtime",
            "noticed", "detect", "detection"),
    "RQ8": ("unknown", "unclassified", "unclassifiable", "coverage", "insufficient",
            "cannot be classified"),
    "RQ9": ("trend", "over time", "time", "historic", "historical", "mature",
            "year", "changed"),
    "RQ10": ("tool", "tools", "integration", "infrastructure", "stack",
             "tool-heavy", "co-occur"),
}

_METHOD = {
    "RQ1": "Frequency tabulation with Wilson 95% score intervals",
    "RQ2": "Ranking recomputed on confident labels only",
    "RQ3": "Cause-by-type contingency, Cramér's V, per-cell lift",
    "RQ4": "Framework-by-type contingency, composition shares",
    "RQ5": "Blocking-severity rate per framework with intervals",
    "RQ6": "Expert-rule complexity index, monotone trend across tiers",
    "RQ7": "Escape rate per failure type (not runtime-detected)",
    "RQ8": "Residual category accounting and coverage by framework",
    "RQ9": "Year-by-type contingency with multiple-testing control",
    "RQ10": "Strata by tool and orchestration declaration",
}

_CHART = {
    "RQ1": ("label", "proportion"),
    "RQ2": ("label", "proportion"),
    "RQ5": ("label", "proportion"),
    "RQ6": ("label", "proportion"),
    "RQ7": ("label", "proportion"),
    "RQ9": ("label", "proportion"),
}


def route(question: str, limit: int = 3) -> list[dict]:
    """Map a free-text question to research questions, with evidence shown."""
    text = " " + re.sub(r"[^a-z0-9 ]+", " ", question.lower()) + " "

    explicit = re.findall(r"\brq\s?(\d{1,2})\b", text)
    scored: list[dict] = []
    for rq, cues in _INTENTS.items():
        hits = [c for c in cues if f" {c} " in text or f" {c}s " in text]
        score = len(hits)
        if rq.replace("RQ", "") in explicit:
            score += 5
            hits.append("explicit")
        if score:
            scored.append({"rq": rq, "score": score, "matched": hits})

    scored.sort(key=lambda r: (-r["score"], r["rq"]))
    if not scored:
        # No lexical signal: answer the broadest descriptive question and say so
        # rather than pretending the router understood.
        scored = [{"rq": "RQ1", "score": 0, "matched": ["fallback"]}]
        scored[0]["fallback"] = True

    # Only keep questions that match as strongly as the best one. Including a
    # weak secondary match padded every answer with the same RQ1 table, which
    # reads as thoroughness but is noise.
    best = scored[0]["score"]
    scored = [r for r in scored if r["score"] >= best] if best else scored
    top = scored[0]["score"] or 1
    for row in scored:
        row["confidence"] = round(row["score"] / top, 3) if top else 0.0
    return scored[:limit]


