"""HTTP surface for the agentic analysis application.

What this is
------------
The study already contains a working multi-agent system: a planner that decides
which questions are answerable, specialist agents that compute each one, a critic
that recomputes headline numbers on an independent path and sends failures back
for revision, and a reporter. Until now it could only be driven from a terminal.

This module exposes that engine over HTTP so it can be used as an application:
ask a question, watch the agents run, read the verified numbers. Nothing here
re-implements statistics; every figure comes from ``afs.analysis`` through the
agents, so the web surface and the manuscript cannot disagree.

Design notes
------------
* **Deterministic routing.** A question is mapped to research questions by
  keyword scoring, not by a language model. The mapping is visible in the
  response, so a reader can see why a question was answered by RQ4 rather than
  RQ1. No number is generated by a model anywhere in this path.
* **Bounded work.** Public endpoint on a shared host, so concurrent analysis
  runs are capped by a semaphore and each client is rate limited. One request
  cannot monopolise the machine.
* **Streaming.** ``/api/ask/stream`` emits server-sent events as each agent acts,
  which is what makes the run observable rather than a five-second pause.
"""
