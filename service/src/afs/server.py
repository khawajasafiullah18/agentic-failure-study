# Narrative
# --------------------------------------------------------------------------- #
def _narrative(rq: str, result: dict, n: int) -> str:
    """Plain-language reading of a verified result.

    Templates only. Every clause is derived from computed values, so the prose
    cannot drift from the table beside it.
    """
    rows = result.get("table") or []
    m = result.get("metrics") or {}

    if rq in ("RQ1", "RQ2") and rows:
        top = rows[0]
        unknown = sum(r["count"] for r in rows if r.get("code") == "A10_unknown")
        return (f"The largest category is {top['label'].lower()}: {top['count']:,} of "
                f"{n:,} records ({top['proportion'] * 100:.1f}%, 95% CI "
                f"{top['ci_low'] * 100:.1f}–{top['ci_high'] * 100:.1f}%). The "
                f"denominator retains the {unknown} unclassified records, so the "
                f"shares cannot be inflated by dropping the hard cases.")
    if rq == "RQ3":
        dem = m.get("demonstrated_causes", 0)
        return (f"Type and stated cause are associated (Cramér's V = "
                f"{m.get('cramers_v', 0):.3f}, χ² = {m.get('chi2', 0):.0f}). This is "
                f"an association in reported text, not an identified mechanism. "
                f"Only {dem:,} records ({dem / n * 100:.1f}%) name a checkable "
                f"mechanism; the rest are graded supported or hypothesised, and no "
                f"causal claim rests on them.")
    if rq == "RQ4":
        return (f"Framework and failure type are associated (Cramér's V = "
                f"{m.get('cramers_v', 0):.3f}) across {m.get('n_frameworks', 0)} "
                f"frameworks. Frameworks do not share one dominant category, so this "
                f"describes composition rather than quality.")
    if rq == "RQ5":
        return (f"Blocking-severity rate ranges from "
                f"{m.get('min_rate', 0) * 100:.1f}% to {m.get('max_rate', 0) * 100:.1f}% "
                f"across frameworks. A low rate can mean graceful degradation or "
                f"silent wrong answers, so pair this with the escape rate.")
    if rq == "RQ6" and rows:
        return (f"The share of orchestration and context failures rises from "
                f"{rows[0]['proportion'] * 100:.1f}% at the lowest complexity tier to "
                f"{rows[-1]['proportion'] * 100:.1f}% at the highest (Spearman ρ = "
                f"{(m.get('trend') or {}).get('rho', 0):.2f}). Complexity relocates "
                f"the failure surface toward coordination; the data do not show it "
                f"shrinking the failure count.")
    if rq == "RQ7":
        return (f"{m.get('escape_share', 0) * 100:.1f}% of records were not reported "
                f"as caught by the framework runtime. These reached a user as wrong "
                f"output rather than as an error, which is why output validation "
                f"matters more than exception monitoring alone.")
    if rq == "RQ8":
        return (f"{m.get('coverage', 0) * 100:.1f}% of records carry a definite "
                f"category; {m.get('unknown', 0)} are coded unknown and stay in every "
                f"denominator instead of being dropped.")
    if rq == "RQ9":
        return (f"Composition changes across {len(m.get('years_analysed') or [])} "
                f"years (V = {m.get('cramers_v', 0):.3f}, χ² = {m.get('chi2', 0):.1f}). "
                f"Collection volume grew over the same period, so this is a change in "
                f"what was reported, not a measured improvement in reliability.")
    if rq == "RQ10":
        return (f"Failure type is associated with the declared stack (V = "
                f"{m.get('cramers_v', 0):.3f}). Stacks that declare tool use carry "
                f"more tool-integration failures, which locates the failure surface "
                f"at the component boundary rather than inside the model.")
    return result.get("note", "")


# --------------------------------------------------------------------------- #
# A single question run, observable while it executes
# --------------------------------------------------------------------------- #
class QuestionRun:
    """Executes the real agents for one question and exposes the trace."""

    def __init__(self, question: str) -> None:
        self.id = uuid.uuid4().hex[:12]
        self.question = question
        self.started = time.time()
        self.finished = 0.0
        self.routed = route(question)
        self.error: str | None = None
        self.done = False
        self.findings: list[dict] = []
        self._cursor = 0
        recs = records()
        self.bb = Blackboard(recs, rq_config())
        self._agents = {
            "StatisticianAgent": StatisticianAgent().attach(self.bb),
            "CausalAgent": CausalAgent().attach(self.bb),
            "ComparatorAgent": ComparatorAgent().attach(self.bb),
            "ComplexityAgent": ComplexityAgent().attach(self.bb),
        }
        self.planner = PlannerAgent().attach(self.bb)
        self.tagger = TaggerAgent().attach(self.bb)
        self.critic = CriticAgent().attach(self.bb)

    # -- trace ------------------------------------------------------------- #
    def new_events(self) -> list[dict]:
        events = self.bb.events
        if self._cursor >= len(events):
            return []
        out = events[self._cursor:]
        self._cursor = len(events)
        return out

    def snapshot(self) -> dict:
        return {
            "run_id": self.id,
            "question": self.question,
            "routed": self.routed,
            "fallback": any(r.get("fallback") for r in self.routed),
            "done": self.done,
            "error": self.error,
            "elapsed_ms": int(((self.finished or time.time()) - self.started) * 1000),
            "findings": self.findings,
            "summary": {
                "questions_answered": len(self.findings),
                "verified": sum(1 for f in self.findings if f["decision"] == "accept"),
                "rejections": sum(1 for f in self.findings if f["decision"] != "accept"),
                "messages": len(self.bb.messages),
                "tool_calls": len(self.bb.tool_calls),
            },
        }

    # -- execution --------------------------------------------------------- #
    def execute(self) -> None:
        try:
            bb = self.bb
            questions = {q["id"]: q for q in self.bb.rq_config["questions"]}
            routed_ids = [r["rq"] for r in self.routed if r["rq"] in questions]

            self.tagger.run({})
            fallback = any(r.get("fallback") for r in self.routed)
            bb.log("PlannerAgent", "routing",
                   routed=routed_ids,
                   fallback=fallback,
                   reason=("no lexical match for the question; falling back to the "
                           "broadest descriptive question"
                           if fallback else
                           ", ".join(f"{r['rq']} (matched: {', '.join(r['matched'][:3])})"
                                     for r in self.routed)))
            bb.post(self._message(
                "PlannerAgent", "Orchestrator", "inform",
                ("No research question matched this wording. Answering RQ1, the "
                 "broadest descriptive question, and labelling it as a fallback."
                 if fallback else
                 f"Question routed to {', '.join(routed_ids)} on lexical evidence. "
                 f"Each will be computed, then recomputed by the critic.")))

            for rq in routed_ids:
                spec = questions[rq]
                owner_name = PlannerAgent._OWNER.get(rq, "StatisticianAgent")
                owner = self._agents.get(owner_name)
                if owner is None:
                    continue
                step = {"rq": rq, "question": spec["question"],
                        "owner": owner_name, "method": spec.get("method", "")}
                result = owner.run(step)
                verdict = self.critic.verify({"rq": rq})
                if verdict["decision"] != "accept":
                    bb.log("Orchestrator", "revision_requested", rq=rq,
                           issues=verdict["issues"])
                    result = owner.run(step)
                    verdict = self.critic.verify({"rq": rq})

                self.findings.append(self._finding(rq, spec, result, verdict, owner_name))

            bb.log("Orchestrator", "run_finished",
                   answered=len(self.findings),
                   verified=sum(1 for f in self.findings if f["decision"] == "accept"))
        except Exception as exc:  # noqa: BLE001 - surfaced to the client
            self.error = f"{type(exc).__name__}: {exc}"
            self.bb.log("Orchestrator", "run_failed", error=self.error)
        finally:
            self.finished = time.time()
            self.done = True

    def _message(self, sender, recipient, act, content):
        from .agents import Message
        return Message(sender, recipient, act, content)

    def _finding(self, rq, spec, result, verdict, owner) -> dict:
        n = len(self.bb.records)
        chart = None
        key_x, key_y = _CHART.get(rq, (None, None))
        rows = result.get("table") or []
        if key_x and rows and key_x in rows[0] and key_y in rows[0]:
            chart = {
                "label_key": key_x,
                "value_key": key_y,
                "is_proportion": key_y in ("proportion", "share"),
                "rows": [{key_x: r[key_x], key_y: r[key_y]} for r in rows],
            }
        return {
            "rq": rq,
            "question": spec["question"],
            "method": spec.get("method") or _METHOD.get(rq, ""),
            "owner": owner,
            "agents": spec.get("agents", []),
            "agent_mode": spec.get("agent_mode", "chain"),
            "decision": verdict["decision"],
            "issues": verdict["issues"],
            "recomputed": verdict.get("recomputed", {}),
            "metrics": result.get("metrics", {}),
            "table": rows,
            "note": result.get("note", ""),
            "narrative": _narrative(rq, result, n),
            "chart": chart,
        }


# --------------------------------------------------------------------------- #
# Concurrency and rate limiting
# --------------------------------------------------------------------------- #
_RUN_SLOTS = threading.Semaphore(2)          # at most two analyses at once
_HITS: dict[str, collections.deque] = {}
_HITS_LOCK = threading.Lock()
_WINDOW, _LIMIT = 60.0, 30

RUNS: dict[str, QuestionRun] = {}
_RUNS_LOCK = threading.Lock()


def _throttle(ip: str) -> None:
    now = time.time()
    with _HITS_LOCK:
        dq = _HITS.setdefault(ip, collections.deque())
        while dq and now - dq[0] > _WINDOW:
            dq.popleft()
        if len(dq) >= _LIMIT:
            raise HTTPException(429, "Too many requests. Wait a minute and retry.")
        dq.append(now)


def _client(request: Request) -> str:
    fwd = request.headers.get("x-forwarded-for", "")
    return (fwd.split(",")[0].strip() or request.client.host) if fwd else (
        request.client.host if request.client else "unknown")


