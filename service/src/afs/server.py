@app.get("/api/export/{rq}.csv")
def export_csv(rq: str, question: str = ""):
    """Re-run one question and return its table as CSV."""
    if rq not in _INTENTS:
        raise HTTPException(404, "Unknown question.")
    if not _RUN_SLOTS.acquire(timeout=20):
        raise HTTPException(503, "Busy, try again shortly.")
    try:
        run = QuestionRun(question or rq)
        run.routed = [{"rq": rq, "score": 99, "matched": ["explicit"],
                       "confidence": 1.0}]
        run.execute()
        if not run.findings:
            raise HTTPException(500, "No result.")
        rows = run.findings[0]["table"]
        buf = io.StringIO()
        writer = csv.DictWriter(buf, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)
        return PlainTextResponse(
            buf.getvalue(), media_type="text/csv",
            headers={"Content-Disposition":
                     f'attachment; filename="{rq.lower()}_table.csv"'})
    finally:
        _RUN_SLOTS.release()


