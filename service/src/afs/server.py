def records() -> list[dict]:
    """Analysis-ready records.

    The enriched file is what the CLI analyses: it carries the derived
    ``complexity_tier`` that RQ6 needs. A bundle is shipped with the deployment
    so the server does not need the raw text corpus at runtime, which also keeps
    that text off the public host entirely.
    """
    global _records
    with _lock:
        if _records is None:
            enriched = PROC_DIR / "records_enriched.jsonl"
            if enriched.exists():
                _records = read_jsonl(enriched)
            else:
                from .analysis import load_records
                _records = load_records()
        return _records


def rq_config() -> dict:
    global _rq_config
    with _lock:
        if _rq_config is None:
            _rq_config = load_rq_config()
        return _rq_config


