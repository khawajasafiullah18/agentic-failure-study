@app.post("/api/ask")
def ask(request: Request, payload: dict) -> dict:
    _throttle(_client(request))
    question = (payload or {}).get("question", "").strip()
    if not question:
        raise HTTPException(400, "Ask a question.")
    if len(question) > 500:
        raise HTTPException(400, "Question is too long (500 characters max).")

    if not _RUN_SLOTS.acquire(timeout=25):
        raise HTTPException(503, "Two analyses are already running. Try again shortly.")
    try:
        run = QuestionRun(question)
        with _RUNS_LOCK:
            RUNS[run.id] = run
            if len(RUNS) > 200:
                for key in list(RUNS)[:100]:
                    RUNS.pop(key, None)
        run.execute()
        return run.snapshot()
    finally:
        _RUN_SLOTS.release()


@app.get("/api/ask/stream")
def ask_stream(request: Request, question: str = Query(..., max_length=500)):
    """Server-sent events: agent trace first, then the findings."""
    _throttle(_client(request))
    question = question.strip()
    if not question:
        raise HTTPException(400, "Ask a question.")
    if not _RUN_SLOTS.acquire(timeout=25):
        raise HTTPException(503, "Two analyses are already running. Try again shortly.")

    run = QuestionRun(question)
    with _RUNS_LOCK:
        RUNS[run.id] = run
    thread = threading.Thread(target=run.execute, daemon=True)
    thread.start()

    def gen():
        try:
            yield _sse("open", {"run_id": run.id, "question": question,
                                "routed": run.routed})
            while True:
                for ev in run.new_events():
                    yield _sse("agent", ev)
                if run.done:
                    for ev in run.new_events():
                        yield _sse("agent", ev)
                    yield _sse("done", run.snapshot())
                    break
                time.sleep(0.06)
        except (GeneratorExit, BrokenPipeError, ConnectionError):
            # The client went away; the run finishes on its own thread.
            pass
        finally:
            _RUN_SLOTS.release()

    return StreamingResponse(gen(), media_type="text/event-stream",
                             headers={"Cache-Control": "no-cache",
                                      "X-Accel-Buffering": "no",
                                      "Connection": "keep-alive"})


def _sse(event: str, data: dict) -> str:
    return f"event: {event}\ndata: {json.dumps(data, default=str)}\n\n"


@app.get("/api/run/{run_id}")
def get_run(run_id: str) -> dict:
    run = RUNS.get(run_id)
    if not run:
        raise HTTPException(404, "No such run.")
    return run.snapshot()


