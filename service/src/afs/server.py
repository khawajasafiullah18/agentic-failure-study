_LABELS: dict[str, dict] = {}
for _dim, _key in (("a", "A_failure_type"), ("b", "B_cause_class"),
                   ("c", "C_lifecycle_stage"), ("d", "D_severity"),
                   ("e", "E_detection_point")):
    _tax = Taxonomy()
    _LABELS[_dim] = {code: _tax.label(_key, code) for code in _tax.codes(_key)}


@app.get("/api/corpus")
def corpus(q: str = Query("", max_length=200), framework: str = "",
           failure_type: str = "", severity: str = "",
           page: int = 1, size: int = Query(20, ge=1, le=100)) -> dict:
    needle = q.strip().lower()
    out = []
    for r in records():
        if framework and r["framework"] != framework:
            continue
        if failure_type and r["A_failure_type"] != failure_type:
            continue
        if severity and r["D_severity"] != severity:
            continue
        if needle:
            blob = " ".join(str(r.get(k) or "") for k in
                            ("title", "A_evidence", "B_cause_class", "framework"))
            if needle not in blob.lower():
                continue
        out.append(r)
    total = len(out)
    start = (page - 1) * size
    rows = [{
        "record_id": r["record_id"],
        "title": r.get("title", ""),
        "framework": r["framework"],
        "url": r.get("url", ""),
        "created_at": (r.get("created_at") or "")[:10],
        "failure_type": r["A_failure_type"],
        "failure_type_label": _LABELS["a"].get(r["A_failure_type"], ""),
        "cause": _LABELS["b"].get(r["B_cause_class"], ""),
        "severity": _LABELS["d"].get(r["D_severity"], ""),
        "evidence": (r.get("A_evidence") or "")[:300],
        "confidence": r.get("A_confidence", 0),
    } for r in out[start:start + size]]

    return {"total": total, "page": page, "size": size,
            "pages": max(1, (total + size - 1) // size), "rows": rows,
            "labels": {"a": _LABELS["a"], "b": _LABELS["b"],
                       "d": _LABELS["d"], "e": _LABELS["e"]}}


@app.get("/api/corpus/{record_id}")
def record(record_id: str) -> dict:
    for r in records():
        if r["record_id"] == record_id:
            dims = (("a", "A_failure_type"), ("b", "B_cause_class"),
                    ("c", "C_lifecycle_stage"), ("d", "D_severity"),
                    ("e", "E_detection_point"))
            return {**r,
                    "labels": {key: _LABELS[dim].get(r.get(key), "")
                               for dim, key in dims}}
    raise HTTPException(404, "No such record.")


